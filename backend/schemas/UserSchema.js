const { Schema } = require("mongoose");

const UserSchema = new Schema({

  username: {
    type: String,
    required: true,
    trim: true,
  },

  email: {
    type: String,
    required: true,
    unique: true,
    lowercase: true,
    trim: true,
  },

  password: {
    type: String,
    required: true,
  },

});

module.exports = { UserSchema };